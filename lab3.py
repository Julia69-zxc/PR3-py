"""
Лабораторная работа № 3. Условный оператор if. Вариант 1.

Задание 1. Вывод цифр пятизначного числа, каждой в новой строке.
Задание 2. Принадлежность точки (x; y) заштрихованной области.
Задание 3. Существование и тип треугольника по трём сторонам.
"""


def task1():
    """Задание 1: каждая цифра пятизначного числа - в новой строке."""
    n = int(input("Введите пятизначное число: "))
    m = abs(n)

    if 10000 <= m <= 99999:
        d1 = m // 10000          
        d2 = m // 1000 % 10      
        d3 = m // 100 % 10       
        d4 = m // 10 % 10        
        d5 = m % 10              
        print(d1)
        print(d2)
        print(d3)
        print(d4)
        print(d5)
    else:
        print("Ошибка: введённое число не является пятизначным")


def task2():
    """Задание 2: принадлежность точки заштрихованной области.

    Область ограничена: окружностью x^2 + y^2 = 4 (точки вне круга),
    прямой x = 2 (слева от неё), прямой y = x (ниже неё) и осью Ox (выше неё).
    """
    x = float(input("Введите x: "))
    y = float(input("Введите y: "))

    if x ** 2 + y ** 2 >= 4 and x <= 2 and 0 <= y <= x:
        print("Точка принадлежит заштрихованной области")
    else:
        print("Точка не принадлежит заштрихованной области")


def task3():
    """Задание 3: могут ли a, b, c быть сторонами треугольника и какого он типа."""
    a = float(input("Введите сторону a: "))
    b = float(input("Введите сторону b: "))
    c = float(input("Введите сторону c: "))

    if a <= 0 or b <= 0 or c <= 0:
        print("Треугольник не существует: длины сторон должны быть положительными")
    elif a + b < c or a + c < b or b + c < a:
        print("Треугольник не существует: нарушено неравенство треугольника")
    elif a + b == c or a + c == b or b + c == a:
        print("Невырожденного треугольника нет: вырожденный случай (площадь равна нулю)")
    else:
        if a == b == c:
            print("Треугольник равносторонний")
        elif a == b or a == c or b == c:
            print("Треугольник равнобедренный")
        else:
            print("Треугольник разносторонний")


def main():
    tasks = {"1": task1, "2": task2, "3": task3}
    while True:
        print()
        print("ЛР3, вариант 1")
        print("1 - Цифры пятизначного числа")
        print("2 - Точка в заштрихованной области")
        print("3 - Тип треугольника")
        print("0 - Выход")
        choice = input("Выберите задание: ")
        if choice == "0":
            break
        if choice in tasks:
            tasks[choice]()
        else:
            print("Нет такого пункта меню")


if __name__ == "__main__":
    main()
